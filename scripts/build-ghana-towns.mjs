// Usage: node scripts/build-ghana-towns.mjs <path-to-GH.txt>
// Generates supabase/functions/_shared/ghana_towns.ts from the GeoNames GH dump.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const CAPITALS = ["Accra","Kumasi","Sekondi-Takoradi","Cape Coast","Koforidua","Ho","Dambai","Tamale","Damongo","Nalerigu","Bolgatanga","Wa","Sunyani","Techiman","Goaso","Sefwi Wiawso"];
const ALIASES = { Bolgatanga: ["Bolga"] };
// GeoNames spellings that differ from the common Ghanaian ones. Applied before keys are made;
// the GeoNames spelling is kept as an alias so IP results using it still match.
const DISPLAY_NAMES = {
  "Obuase": "Obuasi",
  "Wankyi": "Wenchi",
  "Medina Estates": "Madina",
  "Domaa-Ahenkro": "Dormaa Ahenkro",
  "Yegyi": "Yeji",
  "Kpandu": "Kpando",
  "Mankesim": "Mankessim",
};
const MIN_POPULATION = 15000;
const RANK = { PPLC: 2, PPLA: 1 };

const input = process.argv[2];
if (!input) { console.error("Usage: node scripts/build-ghana-towns.mjs <path-to-GH.txt>"); process.exit(1); }

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const capitalKeys = new Set(CAPITALS.map(slug));

const best = new Map();
for (const line of readFileSync(input, "utf8").split("\n")) {
  const c = line.split("\t");
  if (c.length < 15) continue;
  const name = c[2 - 1], ascii = c[3 - 1] || name;
  const lat = parseFloat(c[5 - 1]), lng = parseFloat(c[6 - 1]);
  const cls = c[7 - 1], code = c[8 - 1], pop = parseInt(c[15 - 1], 10) || 0;
  if (cls !== "P" || code === "PPLX") continue;
  const display = DISPLAY_NAMES[ascii] ?? ascii;
  const key = slug(display);
  if (!key || Number.isNaN(lat) || Number.isNaN(lng)) continue;
  if (pop < MIN_POPULATION && !capitalKeys.has(key)) continue;
  const cur = best.get(key);
  const better = !cur || pop > cur.pop || (pop === cur.pop && (RANK[code] ?? 0) > (RANK[cur.code] ?? 0));
  if (better) best.set(key, { key, name: display, alias: display !== ascii ? ascii : null, lat, lng, pop, code });
}

const missing = CAPITALS.filter((c) => !best.has(slug(c)));
if (missing.length) { console.error("Missing capitals: " + missing.join(", ")); process.exit(1); }

const towns = [...best.values()].sort((a, b) => a.name.localeCompare(b.name));
const rows = towns.map((t) => `  { key: ${JSON.stringify(t.key)}, name: ${JSON.stringify(t.name)}, lat: ${t.lat}, lng: ${t.lng}, aliases: ${JSON.stringify([...(ALIASES[t.name] ?? []), ...(t.alias ? [t.alias] : [])])} },`);
const out = `// GENERATED by scripts/build-ghana-towns.mjs - do not edit by hand.
// Source: GeoNames (https://www.geonames.org), licensed CC BY 4.0.
export interface Town { key: string; name: string; lat: number; lng: number; aliases: string[] }

export const GHANA_TOWNS: Town[] = [
${rows.join("\n")}
];
`;
const target = resolve(dirname(fileURLToPath(import.meta.url)), "../supabase/functions/_shared/ghana_towns.ts");
writeFileSync(target, out);
console.log(`Wrote ${towns.length} towns to ${target}`);
